import { redactTraceText } from './redacted-trace.mjs';

export const COPILOT_TERMINAL_FAILURE = /\[input error\]|\[error\]|bwrap:|Agent process exited repeatedly|open \/proc\/\d+\/ns|recovery[_ -]required|Marketplace.*recovery|\b421\b|UNKNOWN_HOST|Misdirected Request|tier[_\s-]+exhausted|All models in tier exhausted|provider\s+(?:error|failure)|API\s+(?:error|failure)|startup\s+(?:error|failure)/i;

// WebChat opens one EventSource per page on `<base>/stream?tabId=<id>&pageInstanceId=...&<agent query>`, where the base
// path is `/webchat` and the id is the page's `webchat_tab_id` browser id, a UUID generated by the page
// (ploinky cli/server/webchat/domSetup.js createBrowserId, network.js `stream?tabId=`, handlers/webchat/index.js
// `__BASE_PATH__`). The RoboTeam diagnostics join a turn to this id as `sourceTabId`.
export const WEBCHAT_STREAM_PATH = '/webchat/stream';
const TAB_ID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/;

export function createCopilotDiagnostics({ now = () => new Date().toISOString(), webchatTab = false } = {}) {
    const evidence = { firstTerminalError: null, submissions: [], replyOutcome: 'not-submitted' };
    // Opt-in: callers that do not ask keep the artifact exactly as it was.
    const tab = webchatTab ? { observationStartedAt: null, tabId: null, status: 'not-observed', streamRequests: 0, distinctTabIds: 0, navigationsAfterBinding: 0, submissionAttempts: [] } : null;
    if (tab) evidence.webchatTab = tab;
    const identities = new Set();
    let stopObserving = null;
    return {
        evidence,
        // Observes only this page's main frame, the configured origin and the selected agent's `/webchat/stream` GET.
        // Only the opaque tab id and counts are kept: no URL, cookie, header, prompt or other query value.
        observeWebchatTab(page, { baseURL, agent }) {
            if (!tab) throw new Error('WebChat tab observation was not enabled for these diagnostics.');
            if (stopObserving) throw new Error('WebChat tab observation is already running.');
            const origin = new URL(baseURL).origin;
            // Taken before any connection can be set up.
            tab.observationStartedAt = now();
            tab.status = 'waiting';
            const onRequest = (request) => {
                if (request.frame() !== page.mainFrame() || request.method() !== 'GET') return;
                const url = new URL(request.url());
                if (url.origin !== origin || url.pathname !== WEBCHAT_STREAM_PATH || url.searchParams.get('agent') !== agent) return;
                tab.streamRequests += 1;
                const id = url.searchParams.get('tabId');
                // An invalidated binding is never rebound: a replaced document has to be started over explicitly.
                if (tab.status === 'invalidated') return;
                if (!TAB_ID.test(id || '')) { tab.status = 'invalid'; return; }
                identities.add(id);
                tab.distinctTabIds = identities.size;
                if (identities.size === 1) { tab.tabId = id; if (tab.status !== 'invalid') tab.status = 'observed'; } else { tab.tabId = null; tab.status = 'ambiguous'; }
            };
            // Authentication navigations before the first stream are expected. Once a stream has been observed, any later
            // main-frame navigation replaces or may replace the document that owns the id, so the binding is invalidated.
            const onNavigated = (frame) => {
                if (frame !== page.mainFrame() || tab.streamRequests === 0) return;
                tab.navigationsAfterBinding += 1;
                tab.tabId = null;
                tab.status = 'invalidated';
            };
            page.on('request', onRequest);
            page.on('framenavigated', onNavigated);
            stopObserving = () => { page.off('request', onRequest); page.off('framenavigated', onNavigated); };
        },
        stopWebchatTab() { stopObserving?.(); stopObserving = null; },
        // The one tab id of this page's owned stream, or a clear failure: missing, malformed, or more than one id.
        requireWebchatTab() {
            if (!tab) throw new Error('WebChat tab observation was not enabled for these diagnostics.');
            if (tab.status === 'observed' && tab.distinctTabIds === 1) return tab.tabId;
            throw new Error(`The WebChat tab identity is ${tab.status === 'waiting' ? 'missing' : tab.status}: ${tab.streamRequests} owned stream request(s), ${tab.distinctTabIds} distinct tab id(s).`);
        },
        // Immediately before the Send click; the identity must already be bound so the turn is attributable.
        beforeSubmit() {
            if (tab) {
                this.requireWebchatTab();
                tab.submissionAttempts.push({ at: now() });
            }
        },
        observe(texts) {
            const failure = texts.find(text => COPILOT_TERMINAL_FAILURE.test(text));
            if (failure && !evidence.firstTerminalError) {
                evidence.firstTerminalError = { at: now(), message: redactTraceText(failure).slice(0, 2048) };
            }
            if (failure) {
                evidence.replyOutcome = 'terminal-error';
                throw new Error(`Copilot terminal initialization/completion failed: ${evidence.firstTerminalError.message}`);
            }
        },
        submitted() { evidence.submissions.push({ at: now() }); evidence.replyOutcome = 'waiting'; },
        replied() { evidence.replyOutcome = 'assistant-reply'; },
        timedOut() { evidence.replyOutcome = 'no-reply'; },
    };
}
