#!/usr/bin/env node
// Regenerates transport-v1.json after T0 amendment A11.1 (required `leaseId` ticket claim). Independent construction:
// recursive ASCII key sorting, SHA-256, HMAC-SHA256 and RFC 5869 extract/expand from node:crypto, without robo-work
// imports. Literal inputs (identities, secret, session key, frame headers and bodies) are read from the previous corpus;
// every derived byte string is recomputed here. Tests never regenerate: they compare against the committed literals.
//
//   node gen-transport-v1.mjs <previous transport-v1.json> <out.json>
import crypto from 'node:crypto';
import fs from 'node:fs';

const [inputPath, outPath] = process.argv.slice(2);
if (!inputPath || !outPath) {
    process.stderr.write('usage: gen-transport-v1.mjs <previous.json> <out.json>\n');
    process.exit(2);
}
const corpus = JSON.parse(fs.readFileSync(inputPath, 'utf8'));
const canonical = (value) => {
    if (Array.isArray(value)) return `[${value.map(canonical).join(',')}]`;
    if (value !== null && typeof value === 'object') return `{${Object.keys(value).sort().map((key) => `${JSON.stringify(key)}:${canonical(value[key])}`).join(',')}}`;
    return JSON.stringify(value);
};
const sha256 = (data) => crypto.createHash('sha256').update(data).digest();
const hmac = (key, ...parts) => parts.reduce((mac, part) => mac.update(part), crypto.createHmac('sha256', key)).digest();
const b64 = (data) => Buffer.from(data).toString('base64url');

// The lease every frame of the corpus already names.
const leaseId = corpus.frames[0].header.leaseId;
if (!corpus.frames.every((frame) => frame.header.leaseId === leaseId)) throw new Error('frames disagree on the lease');
const ticket = corpus.ticket;
const claims = {};
for (const [key, value] of Object.entries(ticket.claims)) {
    claims[key] = value;
    if (key === 'reservationId') claims.leaseId = leaseId;
}
const claimsCanonical = canonical(claims);
const claimsDigest = sha256(Buffer.from(claimsCanonical, 'utf8'));
const secret = Buffer.from(ticket.secretHex, 'hex');
const signingInput = `${b64(Buffer.from(ticket.headerCanonical, 'utf8'))}.${b64(Buffer.from(claimsCanonical, 'utf8'))}`;
const signature = hmac(secret, signingInput);
const expected = {};
for (const [key, value] of Object.entries(ticket.expected)) {
    expected[key] = value;
    if (key === 'reservationId') expected.leaseId = leaseId;
}
corpus.ticket = {
    ...ticket, claims, claimsCanonical, claimsDigest: claimsDigest.toString('hex'), hkdfSaltHex: claimsDigest.toString('hex'), signingInput,
    signatureHex: signature.toString('hex'), compactJws: `${signingInput}.${b64(signature)}`, expected
};
const sessionKey = Buffer.from(corpus.sessionKeyHex, 'hex');
const prk = hmac(claimsDigest, sessionKey);
corpus.hkdfExtractHex = prk.toString('hex');
const domain = Buffer.from(corpus.frameMacDomainHex, 'hex');
corpus.frames = corpus.frames.map((frame) => {
    // RFC 5869 expand for one 32-byte block: T(1) = HMAC(PRK, info || 0x01).
    const key = hmac(prk, Buffer.from(frame.direction, 'ascii'), Buffer.from([1]));
    const prefix = Buffer.from(frame.prefixHex, 'hex');
    const header = Buffer.from(frame.headerCanonical, 'utf8');
    const body = Buffer.from(frame.bodyHex, 'hex');
    const mac = hmac(key, domain, prefix, header, body);
    return { ...frame, keyHex: key.toString('hex'), macInputHex: Buffer.concat([domain, prefix, header, body]).toString('hex'), macHex: mac.toString('hex'), encodedHex: Buffer.concat([prefix, header, body, mac]).toString('hex') };
});
corpus.provenance = 'T0 section 8 plus A1.7 and A11.1 (leaseId claim); independently constructed with recursive ASCII key sorting, SHA-256, HMAC-SHA256 and RFC 5869 extract/expand, without application imports (gen-transport-v1.mjs). Expected bytes are literals, never regenerated by the test.';
fs.writeFileSync(outPath, `${JSON.stringify(corpus, null, 2)}\n`);
