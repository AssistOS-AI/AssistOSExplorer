import crypto from 'node:crypto';

// Identifier grammars of the worker coordinator API (RoboWork interface note 2.3) and the
// deterministic identities RoboTeam derives for it. RoboTeam runs in its own container, so
// these are reimplemented here; the tests compare them with the worker's validators.

const BASE64URL = /^[A-Za-z0-9_-]+$/u;
const FLOW_BINDING_ID = /^flow_[0-9a-f]{24}$/u;
const SCHEDULE_BINDING_ID = /^(cron_[0-9a-f]{24})\.r([1-9][0-9]{0,8})$/u;
const REFERENCE_ID = /^[A-Za-z0-9_-]{22,64}$/u;

// An origin request ID is the canonical base64url form of exactly 16 bytes.
export function isOriginId(value) {
    if (typeof value !== 'string' || value.length !== 22 || !BASE64URL.test(value)) return false;
    const bytes = Buffer.from(value, 'base64url');
    return bytes.length === 16 && bytes.toString('base64url') === value;
}

// Worker robot and logical IDs use the same 16-byte form.
export const isInternalId = isOriginId;

export function isOperationId(value) {
    return typeof value === 'string' && value.length === 22 && BASE64URL.test(value);
}

export function isReferenceId(value) {
    return typeof value === 'string' && REFERENCE_ID.test(value);
}

export function isFlowBindingId(value) {
    return typeof value === 'string' && FLOW_BINDING_ID.test(value);
}

// `cron_<id>.r<n>` -> {scheduleId, revision}, otherwise null.
export function parseScheduleBindingId(value) {
    if (typeof value !== 'string') return null;
    const match = SCHEDULE_BINDING_ID.exec(value);
    if (!match) return null;
    const revision = Number(match[2]);
    return Number.isSafeInteger(revision) ? { scheduleId: match[1], revision } : null;
}

export function isBindingId(value) {
    return isFlowBindingId(value) || parseScheduleBindingId(value) !== null;
}

// The grant RoboTeam forwards to the worker: the `providerAdmission` entry the Router minted
// (manifest key of the `/api/worker/*` route and of `webchat`). The Router verifies the grant's
// signature on the hop; RoboTeam reads its unverified payload only to refuse a grant that names a
// different user than the verified request or envelope, because the worker records the grant's
// user as the owner while RoboTeam's own checks use the verified principal.
export const GRANT_KEY = 'providerAdmission';
const JWT = /^[A-Za-z0-9_-]+\.([A-Za-z0-9_-]+)\.[A-Za-z0-9_-]+$/u;
const GRANT_LIMIT = 16 * 1024;

export function grantForPrincipal(grants, principal) {
    if (typeof principal !== 'string' || !/^user:.+/u.test(principal)) return null;
    const token = grants && typeof grants === 'object' ? grants[GRANT_KEY]?.token : undefined;
    if (typeof token !== 'string' || token.length > GRANT_LIMIT) return null;
    const match = JWT.exec(token);
    if (!match) return null;
    let payload;
    try {
        payload = JSON.parse(Buffer.from(match[1], 'base64url').toString('utf8'));
    } catch {
        return null;
    }
    if (!payload || typeof payload !== 'object' || payload.typ !== 'user-delegation' || payload.sub !== principal) return null;
    return token;
}

// A fresh origin request ID, generated by the WebChat shim before its first transmission.
export function newOriginId() {
    return crypto.randomBytes(16).toString('base64url');
}

// Design S3c-7: the operation ID of a binding registration, reproducible after a restart so a
// repeated registration returns the recorded receipt.
export function bindOperationId(bindingId) {
    if (!isBindingId(bindingId)) throw new TypeError('a binding ID is required');
    return crypto.createHash('sha256').update(`roboteam/bind/v1\n${bindingId}`).digest('base64url').slice(0, 22);
}
